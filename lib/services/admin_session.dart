/// حالة قفل الأقسام الإدارية خلال تشغيل واحد للتطبيق.
///
/// كان رمز الإدارة يُطلب عند كل دخول لقسم إداري، وهذا إرهاق بلا مقابل
/// أمني حقيقي: بصمة الرمز مخزَّنة داخل ملف التطبيق، ومن يفكّه يستخرجها
/// ويجرّب أربعة أرقام في أجزاء من الثانية. الحماية الفعلية هي صلاحيات
/// قاعدة البيانات (RLS) وجدول `database_admins`.
///
/// الفائدة الحقيقية الوحيدة للرمز: منع من يمسك الهاتف مفتوحاً وحسابك
/// مسجَّل فيه. وهذه تتحقّق بسؤال واحد لكل تشغيل.
///
/// متغيّر في الذاكرة لا في التخزين الدائم: يعود مقفولاً تلقائياً عند
/// إغلاق التطبيق وفتحه، وهذا هو المطلوب بالضبط.
class AdminSession {
  AdminSession._();

  static bool _unlocked = false;

  /// هل يجب سؤال الرمز الآن؟
  static bool get needsPin => !_unlocked;

  static void unlock() => _unlocked = true;

  /// يُستدعى عند تسجيل الخروج فيُقفل الباب فوراً.
  static void reset() => _unlocked = false;
}
